#!/usr/bin/env python3
"""The body lab's tables and wound sheets (README.md).

  python3 experiments/body_lab/report.py gather RUN_ROOT       baseline.json + baseline.md from a run
  python3 experiments/body_lab/report.py sheets RUN_ROOT       RUN_ROOT/sheet_<model>.png from a --render run
  python3 experiments/body_lab/report.py vessels RUN_ROOT      vessels.md from a --vessels run
"""
import json, os, sys
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "physics_lab"))
from compare import label  # the ragdoll lab's tile label  # noqa: E402


ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
KINDS = {st["id"]: st["kind"] for st in json.load(open(os.path.join(ROOT, "config", "anatomy.json")))["structures"]}


def summaries(root):
    out = {}
    for model in sorted(os.listdir(root)):
        d = os.path.join(root, model)
        if not os.path.isdir(d):
            continue
        for sc in sorted(os.listdir(d)):
            f = os.path.join(d, sc, "summary.json")
            if os.path.exists(f):
                out[(model, sc)] = json.load(open(f))
    return out


def t(x):
    """Seconds as m:ss, or - for never."""
    if x is None:
        return "-"
    x = float(x)
    return "%d:%02d" % (x // 60, x % 60) if x >= 60 else "%.0fs" % x


def fate(o):
    if not o.get("reached", True) and o.get("dead_s") is not None:
        return "dead first (%s)" % t(o["dead_s"])
    if not o.get("applicable", True):
        return "n/a"
    if o.get("dead_s") is None:
        return "lives (-%d ml)" % o.get("lost_ml", 0)
    return "%s %s" % (t(o["dead_s"]), o.get("cause", "").replace("blood_loss", "blood").replace("_", " "))


def can(a):
    words = []
    if not a.get("conscious", True):
        words.append("out")
    if not a.get("can_stand", True):
        words.append("can't stand")
    elif not a.get("can_run", True):
        words.append("can't run")
    for side in "rl":
        if not a.get("can_hold_" + side, True):
            words.append("no %s grip" % side.upper())
    if a.get("legs_paralysed"):
        words.append("legs paralysed")
    if not a.get("can_speak", True):
        words.append("can't speak")
    return ", ".join(words) or "fine"


def row(sm):
    sc = sm["scenario"]
    inj = sm["injuries"]
    out = {"scenario": sc["name"], "model": sm["model"], "crossed": sorted(sm.get("crossed", {})),
           "broken": sorted(inj["broken"]), "severed": sorted(inj["severed"]), "fingers": sorted(inj["fingers"]),
           "down": sm["body"]["limp"] or sm["body"]["prone"], "knocked": sm["body"]["knocked_down"],
           "abilities": can(sm["abilities"]), "bleed_ml_s": inj["bleed_ml_s"], "hat_off": sm["body"]["hat_off"],
           "outcomes": {k: fate(v) for k, v in sm["outcomes"].items()},
           "raw_outcomes": sm["outcomes"], "wounds": len(sm.get("wounds", []))}
    if sc["kind"] == "shot":
        a = sm["aim"]
        out.update({"on_target": sm.get("on_target", []), "aim_segment": a["segment"], "aim_crosses": a["aims_for"],
                    "poi_cm": a["point_of_impact_cm"], "joules": a["energy_at_range_j"],
                    "segments_hit": sorted(set(sm.get("segments_hit", []))), "pellets_hit": len(sm.get("hits", []))})
    else:
        out.update({"harm": sorted({h for i in sm.get("hits", []) for h in i.get("harm", [])}),
                    "chest_kpa": sm.get("charge", {}).get("chest_kpa_side_on"),
                    "gravel_toward": len(sm.get("charge", {}).get("projectiles_toward_him_elevation_deg", []))})
    return out


def key(r):
    """What should be the same on every man (the anatomy's numbers, not his mesh)."""
    return json.dumps([r["crossed"], r["broken"], r["severed"], r["fingers"], r["outcomes"], r["abilities"]])


def gather(root):
    sms = summaries(root)
    rows = [row(s) for (m, sc), s in sms.items() if sc != "check" and "scenario" in s and "outcomes" in s]
    checks = {m: s["check"] for (m, sc), s in sms.items() if sc == "check"}
    probes = {m: s["same_tick"] for (m, sc), s in sms.items() if sc == "same_tick"}
    json.dump({"rows": rows, "checks": checks, "same_tick": probes}, open(os.path.join(root, "baseline.json"), "w"))
    md = ["# Body lab baseline", "", "Generated by `report.py gather` from `%s`." % os.path.basename(root.rstrip("/")), ""]
    by_sc = {}
    for r in rows:
        by_sc.setdefault(r["scenario"], []).append(r)
    ref_model = rows[0]["model"] if rows else ""
    md += ["## Shots", "",
           "Aim: share of 200 aimed shots (the game's aimed wobble, and buckshot's pattern) that reach the marked part / cross "
           "what the spot aims for; POI: where a perfect aim lands against the mark (cm, + high). The rest is the one shot "
           "fired with a perfect aim on the first man (`same` says whether every man came out the same).", "",
           "| scenario | J | POI | aim part / target | crossed (this shot) | broke | down | can't | untreated | tourniquet 30 s | packed 30 s | packed + doctor 10 min | same |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for sc in sorted(by_sc, key=lambda s: (s.split("_")[0], s.split("_")[1], s)):
        rs = by_sc[sc]
        r = next((x for x in rs if x["model"] == ref_model), rs[0])
        if "aim_segment" not in r:
            continue
        same = "yes" if len({key(x) for x in rs}) == 1 else "**no**: " + ", ".join(x["model"] for x in rs if key(x) != key(r))
        o = r["outcomes"]
        md.append("| %s | %.0f | %+.0f | %.0f%% / %.0f%% | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            sc, r["joules"], r["poi_cm"], r["aim_segment"] * 100, r["aim_crosses"] * 100,
            ", ".join(c for c in r["crossed"] if KINDS.get(c) != "muscle") or "-",
            ", ".join(r["broken"] + ["%s off" % f for f in r["fingers"]]) or "-", "yes" if r["down"] else "-", r["abilities"],
            o.get("none"), o.get("tourniquet"), o.get("packing"), o.get("doctor"), same))
    md += ["", "## Dynamite (one stick on the ground in front of him)", "",
           "| scenario | chest kPa | harm | gravel toward him | wounds | severed | down | untreated | same |", "|---|---|---|---|---|---|---|---|---|"]
    for sc in sorted(s for s in by_sc if s.startswith("dynamite")):
        rs = by_sc[sc]
        r = next((x for x in rs if x["model"] == ref_model), rs[0])
        same = "yes" if len({key(x) for x in rs}) == 1 else "**no**"
        md.append("| %s | %s | %s | %d | %d | %s | %s | %s | %s |" % (sc, r["chest_kpa"], ", ".join(r["harm"]) or "-",
                  r["gravel_toward"], r["wounds"] - 1, ", ".join(r["severed"]) or "-", "yes" if r["down"] else "-",
                  r["outcomes"].get("none"), same))
    if checks:
        md += ["", "## Each man's check", "",
               "| model | loaded | pieces | wound shows | stump rims open (cm of edge) | limb flew | hat | hat shot off | head hit through the crown | crown clearance | hat in a blast that throws him |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for m, c in sorted(checks.items()):
            st = c["stumps"]
            md.append("| %s | %s | %d | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                m, c["model"]["loaded"], sum(c["model"]["pieces_per_segment"].values()),
                "%d/%d pieces" % (c["wound"]["pieces_showing_it"], c["wound"]["chest_pieces"]),
                "; ".join("%s: stump %s, limb %s" % (s["segment"], s["stump_open_edges"] or "closed", s["limb_end_open_edges"] or "closed") for s in st),
                ", ".join("%.2f m" % s["limb_flew_m"] for s in st),
                "yes" if c["model"]["hat_body"] else "no", c["hat"]["shot_off"] if c["model"]["hat_body"] else "-",
                c["hat"]["head_wounds"] if c["model"]["hat_body"] else "-",
                "%s cm" % c.get("hat_crown_clearance_cm") if c.get("hat_crown_clearance_cm") is not None else "-",
                ("off" if c["hat_in_blast"]["hat_off"] else "stays on") if c["hat_in_blast"]["had_hat"] else "-"))
    if probes:
        md += ["", "## A ball on the tick he goes limp (revolver, his right thigh, 3 m)", "",
               "| model | " + " | ".join(c["case"] for c in next(iter(probes.values()))) + " |",
               "|---|" + "---|" * len(next(iter(probes.values())))]
        for m, cs in sorted(probes.items()):
            md.append("| %s | %s |" % (m, " | ".join("%d wound(s)" % c["wounds"] for c in cs)))
    open(os.path.join(root, "baseline.md"), "w").write("\n".join(md) + "\n")
    print("gathered %d runs into %s" % (len(rows) + len(checks), os.path.join(root, "baseline.md")))


def vessels(root):
    data = json.load(open(os.path.join(root, "vessels.json")))
    md = ["| vessel | kind | ml/s | clots | untreated: out / dead | packed 30 s | packed: lives (40 seeds) | tourniquet 30 s | doctor 10 min |", "|---|---|---|---|---|---|---|---|---|"]
    for v in sorted(data["vessels"], key=lambda v: -v["ml_s"]):
        o = v["outcomes"]
        n = o["none"]
        md.append("| %s | %s | %s | %s | %s / %s | %s | %s | %s | %s |" % (v["id"], v["kind"], v["ml_s"], "yes" if v["clots"] else "no",
                  t(n.get("unconscious_s")), fate(n), fate(o["packing"]),
                  "%.0f%%" % (v.get("packed_lives_share", 0) * 100) if "packed_lives_share" in v else "-",
                  fate(o["tourniquet"]), fate(o["doctor"])))
    open(os.path.join(root, "vessels.md"), "w").write("\n".join(md) + "\n")
    print("vessels into %s" % os.path.join(root, "vessels.md"))


def sheets(root, tile=(320, 240)):
    sms = summaries(root)
    models = sorted({m for m, _ in sms})
    for m in models:
        runs = sorted(sc for mm, sc in sms if mm == m and os.path.isdir(os.path.join(root, m, sc, "frames")))
        tiles = []
        for sc in runs:
            fr = os.path.join(root, m, sc, "frames")
            for f in sorted(os.listdir(fr)):
                im = Image.open(os.path.join(fr, f)).convert("RGB").resize(tile)
                tiles.append(label(im, "%s %s" % (sc, f[:-4])))
        if not tiles:
            continue
        cols = 6
        rows = (len(tiles) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * tile[0], rows * tile[1] + 18), (20, 20, 20))
        ImageDraw.Draw(sheet).text((4, 3), "body lab: %s (%s)" % (m, os.path.basename(root.rstrip("/"))), fill=(255, 255, 255))
        for i, im in enumerate(tiles):
            sheet.paste(im, ((i % cols) * tile[0], 18 + (i // cols) * tile[1]))
        path = os.path.join(root, "sheet_%s.png" % m)
        sheet.save(path)
        print("sheet %s" % path)


def diff(base, cand):
    """Every run whose result changed between two roots (their baseline.json), as a markdown table."""
    def load(root):
        b = json.load(open(os.path.join(root, "baseline.json")))
        rows = {(r["model"], r["scenario"]): r for r in b["rows"]}
        return rows, b.get("checks", {}), b.get("same_tick", {})
    br, bc, bp = load(base)
    cr, cc, cp = load(cand)
    out = ["| run | what changed | before | after |", "|---|---|---|---|"]
    fields = ["crossed", "broken", "severed", "fingers", "down", "abilities", "outcomes", "wounds", "pellets_hit", "harm"]
    for k in sorted(set(br) | set(cr)):
        a, b = br.get(k), cr.get(k)
        if a is None or b is None:
            out.append("| %s %s | only in %s | | |" % (k[0], k[1], "after" if a is None else "before"))
            continue
        for f in fields:
            if a.get(f) != b.get(f):
                out.append("| %s %s | %s | %s | %s |" % (k[1], k[0], f, a.get(f), b.get(f)))
    for m in sorted(set(bp) | set(cp)):
        if bp.get(m) != cp.get(m):
            out.append("| same_tick %s | wounds | %s | %s |" % (m, [c["wounds"] for c in bp.get(m, [])], [c["wounds"] for c in cp.get(m, [])]))
    for m in sorted(set(bc) | set(cc)):
        for part in ("wound", "hat", "hat_in_blast", "stumps"):
            if bc.get(m, {}).get(part) != cc.get(m, {}).get(part):
                out.append("| check %s | %s | %s | %s |" % (m, part, json.dumps(bc.get(m, {}).get(part))[:200], json.dumps(cc.get(m, {}).get(part))[:200]))
    print("\n".join(out))


if __name__ == "__main__":
    if sys.argv[1] == "diff":
        diff(sys.argv[2], sys.argv[3])
    else:
        {"gather": gather, "sheets": sheets, "vessels": vessels}[sys.argv[1]](sys.argv[2])
