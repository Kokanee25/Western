"""The places with height's sheet (#736 B, #752): a dev bridge script that photographs each place
from its high spot (looking at its first target) and from below (from its first target, looking
up at the high spot), and the sheet made from the pictures.

    python3 tools/valley/heights_pictures.py script > experiments/valley/heights_pictures.txt
    python3 tools/bridge.py run experiments/valley/heights_pictures.txt --size=960x540 --game-args=--world=valley --timeout=5400
    python3 tools/valley/heights_pictures.py sheet --out=experiments/valley/results/heights_sheet.jpg

Heights come from the bake (config/valley_ground/) and the blocks' tops as ValleyMarkers stands
them (the highest ground under the block plus its `h`)."""
import gzip
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHOTS = "/tmp/heights_pics"


def bake():
	m = json.load(open(os.path.join(ROOT, "config/valley_ground/heights.json")))
	raw = gzip.decompress(open(os.path.join(ROOT, "config/valley_ground", m["file"]), "rb").read())
	import numpy as np
	h = m["offset"] + m["scale"] * np.frombuffer(raw, "<u2").reshape(m["depth"], m["width"]).astype(float)

	def at(x, z):
		fx = (x - m["x0"]) / m["spacing"]
		fz = (z - m["z0"]) / m["spacing"]
		i, j = int(fx), int(fz)
		tx, tz = fx - i, fz - j
		return float((h[j, i] * (1 - tx) + h[j, i + 1] * tx) * (1 - tz) + (h[j + 1, i] * (1 - tx) + h[j + 1, i + 1] * tx) * tz)
	return at


def block_top(at, hp, b, place_blocks):
	c = b.get("at", hp["at"])
	hd = math.radians(b.get("heading", 90.0))
	ux, uz = math.sin(hd), -math.cos(hd)
	vx, vz = -uz, ux
	hi = -1e9
	for su in (-1, 1, 0):
		for sv in (-1, 1, 0):
			x = c[0] + su * ux * b["w"] * 0.5 + sv * vx * b["d"] * 0.5
			z = c[1] + su * uz * b["w"] * 0.5 + sv * vz * b["d"] * 0.5
			hi = max(hi, at(x, z))
	return hi + b["h"], c, (ux, uz, vx, vz)


def inside(p, c, axes, b):
	ux, uz, vx, vz = axes
	rx, rz = p[0] - c[0], p[1] - c[1]
	return abs(rx * ux + rz * uz) <= b["w"] * 0.5 and abs(rx * vx + rz * vz) <= b["d"] * 0.5


def high_y(at, d, hp):
	x, z = hp["high"]["at"]
	y = at(x, z)
	bl = list(hp.get("blocks", []))
	if hp.get("ladder_on"):
		p = [q for q in d["places"] if q["id"] == hp["ladder_on"]][0]
		bl.append(dict(p["block"], at=p["block"].get("at", p["at"])))
	for b in bl:
		top, c, axes = block_top(at, hp, b, None)
		if inside((x, z), c, axes, b):
			y = max(y, top)
	return y


def script():
	d = json.load(open(os.path.join(ROOT, "config/valley.json")))
	at = bake()
	L = ["# Valley heights (#736 B, #752): each place from its high spot and from below. Real look, lavapipe:",
		"# python3 tools/bridge.py run experiments/valley/heights_pictures.txt --size=960x540 --game-args=--world=valley --timeout=5400",
		"# (generated by tools/valley/heights_pictures.py script)", "wait 30", "time 10.5"]
	for hp in d["heights"]:
		hx, hz = hp["high"]["at"]
		hy = high_y(at, d, hp)
		tx, tz = hp["targets"][0]["at"]
		ty = at(tx, tz)
		# From the high spot: the eye 1.7 m up, a step back from the lip, looking at the target.
		dx, dz = tx - hx, tz - hz
		n = math.hypot(dx, dz)
		ex, ez = hx - dx / n * 1.0, hz - dz / n * 1.0
		L.append("camera %.1f %.2f %.1f %.1f %.2f %.1f" % (ex, hy + 1.7, ez, tx, ty + 1.0, tz))
		L.append("wait 8")
		L.append("screenshot %s/%s_above.png" % (SHOTS, hp["id"]))
		# From below: the first target, the eye 1.7 m up, looking at the high spot.
		L.append("camera %.1f %.2f %.1f %.1f %.2f %.1f" % (tx, ty + 1.7, tz, hx, hy + 1.0, hz))
		L.append("wait 8")
		L.append("screenshot %s/%s_below.png" % (SHOTS, hp["id"]))
	print("\n".join(L))


def sheet(out):
	from PIL import Image, ImageDraw
	d = json.load(open(os.path.join(ROOT, "config/valley.json")))
	W, H = 480, 270
	rows = d["heights"]
	img = Image.new("RGB", (W * 2 + 260, H * len(rows)), "white")
	dr = ImageDraw.Draw(img)
	for i, hp in enumerate(rows):
		dr.text((8, i * H + 8), "%d. %s" % (i + 1, hp.get("short", hp["name"])), fill="black")
		dr.text((8, i * H + 28), "left: from the high spot\nto %s\nright: from there, up" % hp["targets"][0]["name"], fill="#444")
		for k, which in enumerate(("above", "below")):
			p = os.path.join(SHOTS, "%s_%s.png" % (hp["id"], which))
			if os.path.exists(p):
				im = Image.open(p).convert("RGB").resize((W, H))
				img.paste(im, (260 + k * W, i * H))
	img.save(out, quality=85)
	print("wrote", out)


if __name__ == "__main__":
	if len(sys.argv) > 1 and sys.argv[1] == "script":
		script()
	elif len(sys.argv) > 1 and sys.argv[1] == "sheet":
		o = [a.split("=", 1)[1] for a in sys.argv[2:] if a.startswith("--out=")]
		sheet(o[0] if o else os.path.join(ROOT, "experiments/valley/results/heights_sheet.jpg"))
	else:
		print(__doc__)
